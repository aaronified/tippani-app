/// Parses a Tippani locale file: `key = value` per line, `#` for comments, the first `=` splits, `_key` is
/// metadata, an empty value counts as absent. The same rules the server's parser keeps. Plain Dart (no Flutter), so
/// the tool that generates the English table can use it.
({Map<String, String> keys, Map<String, String> reserved}) parseLocale(
  String src,
) {
  final keys = <String, String>{};
  final reserved = <String, String>{};
  var text = src.startsWith('\u{FEFF}') ? src.substring(1) : src;
  text = text.replaceAll('\r\n', '\n').replaceAll('\r', '\n');
  for (final line in text.split('\n')) {
    final s = line.trim();
    if (s.isEmpty || s.startsWith('#')) continue;
    final eq = s.indexOf('=');
    if (eq <= 0) continue;
    final k = s.substring(0, eq).trim();
    final v = s.substring(eq + 1).trim();
    if (k.isEmpty || v.isEmpty) continue;
    if (k.startsWith('_')) {
      reserved[k] = v;
    } else {
      keys[k] = v;
    }
  }
  return (keys: keys, reserved: reserved);
}

/// The app's own files are one line per token, so a line break in a text is written as the two characters
/// backslash and n; this turns them back into a line break. The web's files do not use it.
String unescapeApp(String v) => v.replaceAll(r'\n', '\n');

/// A string as a Dart single-quoted literal.
String dartString(String s) {
  final b = StringBuffer("'");
  for (final r in s.runes) {
    switch (r) {
      case 0x5C:
        b.write(r'\\');
      case 0x27:
        b.write(r"\'");
      case 0x24:
        b.write(r'\$');
      case 0x0A:
        b.write(r'\n');
      case 0x0D:
        b.write(r'\r');
      default:
        b.writeCharCode(r);
    }
  }
  b.write("'");
  return b.toString();
}

/// The text of `lib/l10n/english.g.dart`: every English token, from the server's own file and the app's, as one
/// constant table. Generated so English is there the moment the app starts, with nothing to load.
String englishTable(String serverEn, String appEn) {
  final all = <String, String>{
    ...parseLocale(serverEn).keys,
    for (final e in parseLocale(appEn).keys.entries)
      e.key: unescapeApp(e.value),
  };
  final names = all.keys.toList()..sort();
  final b = StringBuffer()
    ..writeln('// dart format off')
    ..writeln(
      '// GENERATED by tool/gen_l10n.dart. Do not edit: change the text files and run',
    )
    ..writeln('//   dart run tool/gen_l10n.dart')
    ..writeln(
      '// The source is assets/l10n/en.txt (the server\'s English, copied) and assets/l10n/app.en.txt (the',
    )
    ..writeln(
      '// words only the app has). A test fails when this file is out of date.',
    )
    ..writeln()
    ..writeln('/// Every English line, by token.')
    ..writeln('const Map<String, String> englishTokens = {');
  for (final k in names) {
    b.writeln('  ${dartString(k)}: ${dartString(all[k]!)},');
  }
  b.writeln('};');
  return b.toString();
}
